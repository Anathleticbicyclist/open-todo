  /// Resolves a [Locale] to the best supported code.
  static String resolveCode(Locale locale) {
    final lang = locale.languageCode;
    if (lang == 'zh') {
      // Traditional Chinese: script Hant, or TW/HK/MO regions.
      final script = locale.scriptCode;
      final country = locale.countryCode;
      if (script == 'Hant' ||
          country == 'TW' ||
          country == 'HK' ||
          country == 'MO') {
        return 'zh-Hant';
      }
      return 'zh';
    }
    if (supportedCodes.contains(lang)) return lang;
    return 'en';
  }

  /// Locale string suitable for intl DateFormat (e.g. 'zh_TW' for
  /// Traditional Chinese). intl falls back to English for unknown codes,
  /// so this mapping only needs the common cases.
  static String get dateLocale {
    final code = current.languageCode == 'zh' && current.scriptCode == 'Hant'
        ? 'zh-Hant'
        : current.languageCode;
    if (code == 'zh-Hant') return 'zh_TW';
    if (code == 'zh') return 'zh_CN';
    return code;
  }

  static String tr(String key, [Map<String, String>? params]) {
    final code = current.languageCode == 'zh' && current.scriptCode == 'Hant'
        ? 'zh-Hant'
        : current.languageCode;
    var value = _values[code]?[key] ?? _values['en']![key] ?? key;
    if (params != null) {
      params.forEach((k, v) {
        value = value.replaceAll('{$k}', v);
      });
    }
    return value;
  }

